it('resolves admin delete user console translations in english', function () {
    App::setLocale('en');

    expect(trans('console.admin_delete_user.confirm.phase_2_to_3'))
        ->toBe('Phase 2 completed. Continue to Phase 3 (Delete Servers)?')
        ->and(trans('console.admin_delete_user.confirm.phase_5_commit'))
        ->toBe('Phase 5 completed. Commit database changes? (THIS IS PERMANENT)')
        ->and(trans('console.admin_delete_user.commit.next_step'))
        ->toBe('Next step: COMMIT database changes (PERMANENT and IRREVERSIBLE)')
        ->and(trans('console.admin_delete_user.commit.cannot_be_undone'))
        ->toBe('⚠️  THIS ACTION CANNOT BE UNDONE')
        ->and(trans('console.admin_delete_user.recovery.title'))
        ->toBe('RECOVERY STEPS')
        ->and(trans('console.admin_delete_user.user_profile.phase_title'))
        ->toBe('PHASE 5: DELETE USER PROFILE')
        ->and(trans('console.admin_delete_user.user_profile.summary_title'))
        ->toBe('User profile to be deleted:')
        ->and(trans('console.admin_delete_user.user_profile.table_headers.property'))
        ->toBe('Property')
        ->and(trans('console.admin_delete_user.user_profile.fields.email_verified'))
        ->toBe('Email Verified')
        ->and(trans('console.admin_delete_user.user_profile.fields.two_factor_enabled'))
        ->toBe('2FA Enabled')
        ->and(trans('console.admin_delete_user.user_profile.confirmation_instruction', ['confirmation_text' => 'DELETE user@example.com']))
        ->toBe("Type 'DELETE user@example.com' to confirm final deletion:")
        ->and(trans('console.admin_delete_user.user_profile.confirmation_label'))
        ->toBe('Confirmation')
        ->and(trans('console.admin_delete_user.user_profile.confirmation_mismatch'))
        ->toBe('Confirmation text does not match. Deletion cancelled.')
        ->and(trans('console.admin_delete_user.user_profile.deleting'))
        ->toBe('Deleting user profile...')
        ->and(trans('console.admin_delete_user.user_profile.deleted_successfully'))
        ->toBe('✓ User profile deleted successfully.')
        ->and(trans('console.admin_delete_user.user_profile.delete_failed'))
        ->toBe('Failed to delete user profile:')
        ->and(trans('console.admin_delete_user.user_profile.exception_label'))
        ->toBe('Exception')
        ->and(trans('console.admin_delete_user.user_profile.message_label'))
        ->toBe('Message')
        ->and(trans('console.admin_delete_user.user_profile.file_label'))
        ->toBe('File')
        ->and(trans('console.admin_delete_user.user_profile.stack_trace_label'))
        ->toBe('Stack Trace:')
        ->and((new AdminDeleteUser)->getDescription())
        ->toBe('Delete a user with comprehensive resource cleanup and phase-by-phase confirmation (works on cloud and self-hosted)');
});

